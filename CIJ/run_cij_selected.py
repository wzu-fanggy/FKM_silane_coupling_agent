#!/usr/bin/env python3
"""Run Cij strain jobs for user-selected frame(s) only.

The frames must already have been generated by run_cij.py.  Each selected
frame runs its 12 strain jobs sequentially and writes all outputs inside
the existing job directories.

Usage:
    python run_cij_selected.py --frames 5
    python run_cij_selected.py --frames 1,7,20
    python run_cij_selected.py --frames 3-6
    python run_cij_selected.py --frames all
    python run_cij_selected.py --frames 5 --dry-run
"""

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_LMP = r"F:\LAMMPS 64-bit 4Jul2026 with GUI\bin\lmp.exe"
MODES = ["xx", "yy", "zz", "xy", "xz", "yz"]
SIGNS = ["+", "-"]


def available_frames():
    frames = {}
    strain_dir = SCRIPT_DIR / "strain"
    if not strain_dir.is_dir():
        raise SystemExit("missing strain/ directory; run run_cij.py first")
    for d in strain_dir.iterdir():
        if d.is_dir() and d.name.startswith("frame"):
            try:
                frames[int(d.name[5:])] = d
            except ValueError:
                continue
    if not frames:
        raise SystemExit("no frame directories found under strain/")
    return frames


def parse_frames(spec, valid):
    selected = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if part.lower() == "all":
            selected.extend(sorted(valid))
            continue
        if "-" in part:
            lo, hi = part.split("-", 1)
            selected.extend(range(int(lo), int(hi) + 1))
        else:
            selected.append(int(part))
    result = []
    for n in selected:
        if n not in valid:
            raise SystemExit(f"frame {n:02d} not found under strain/")
        if n not in result:
            result.append(n)
    return sorted(result)


def stress_ready(path):
    if not path.exists():
        return False
    try:
        for line in path.read_text(encoding="ascii", errors="ignore").splitlines():
            q = line.split()
            if len(q) >= 7 and q[0].replace(".", "", 1).isdigit():
                return True
    except OSError:
        return False
    return False


def run_lammps(lmp, job_dir, omp, gpu):
    env = dict(os.environ)
    env["OMP_NUM_THREADS"] = str(omp)
    cmd = [lmp, "-in", "in.lammps", "-log", "log.lammps", "-screen", "none"]
    if gpu > 0:
        cmd += ["-sf", "gpu", "-pk", "gpu", str(gpu)]
    t0 = time.perf_counter()
    proc = subprocess.run(
        cmd,
        cwd=str(job_dir),
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    elapsed = time.perf_counter() - t0
    if proc.returncode != 0:
        log = job_dir / "log.lammps"
        tail = ""
        if log.exists():
            tail = "\n".join(
                log.read_text(encoding="ascii", errors="ignore").splitlines()[-25:]
            )
        raise RuntimeError(f"LAMMPS failed in {job_dir}\n{tail}")
    return elapsed


def parse_args():
    parser = argparse.ArgumentParser(
        description="Run Cij jobs for selected frames only."
    )
    parser.add_argument(
        "--frames",
        required=True,
        help="frame numbers, e.g. 5 or 1,7,20 or 3-6 or all",
    )
    parser.add_argument("--lmp", default=DEFAULT_LMP)
    parser.add_argument("--omp", type=int, default=16)
    parser.add_argument("--gpu", type=int, default=1)
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def main():
    args = parse_args()
    if not Path(args.lmp).exists():
        raise SystemExit(f"LAMMPS executable not found: {args.lmp}")

    frames = parse_frames(args.frames, available_frames())
    jobs = []
    for n in frames:
        frame_dir = SCRIPT_DIR / "strain" / f"frame{n:02d}"
        for mode in MODES:
            for sign in SIGNS:
                job_dir = frame_dir / f"{mode}{sign}"
                if not (job_dir / "in.lammps").exists():
                    raise SystemExit(f"missing {job_dir / 'in.lammps'}")
                jobs.append((n, job_dir, mode, sign))

    total = len(jobs)
    print(f"selected frames: {[f'{n:02d}' for n in frames]}")
    print(f"jobs to run: {total} ({len(frames)} frames x 12)")
    if args.gpu == 0:
        print(
            "WARNING: CPU-only mode.  On this machine one 200 ps job "
            "took ~10 h; GPU mode is about 8x faster."
        )
    if args.dry_run:
        for n, job_dir, mode, sign in jobs:
            print(f"  frame{n:02d} {mode}{sign}: {job_dir}")
        return

    if args.gpu > 0:
        print(f"LAMMPS: {args.lmp} | OMP {args.omp} | GPU {args.gpu}")
    else:
        print(f"LAMMPS: {args.lmp} | OMP {args.omp} | CPU only")

    t_all = time.perf_counter()
    done = 0
    for n, job_dir, mode, sign in jobs:
        done += 1
        t0 = time.perf_counter()
        elapsed = run_lammps(args.lmp, job_dir, args.omp, args.gpu)
        out = job_dir / f"stress_{mode}_{sign}.txt"
        status = "ok"
        if not stress_ready(out):
            status = "WARN: stress file missing/empty"
        elapsed_total = time.perf_counter() - t_all
        eta = elapsed_total / done * (total - done) if done else 0.0
        print(
            f"[{done:3d}/{total:3d}] frame{n:02d} {mode}{sign} "
            f"done in {elapsed:7.1f}s | elapsed {elapsed_total:8.1f}s "
            f"| eta {eta:8.1f}s | {status}",
            flush=True,
        )

    print(
        f"finished {total} jobs in {time.perf_counter() - t_all:.1f}s "
        f"({(time.perf_counter() - t_all) / 60.0:.1f} min)"
    )
if __name__ == "__main__":
    main()
